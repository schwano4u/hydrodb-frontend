import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import react from '@vitejs/plugin-react'
import { build } from 'vite'

const root = new URL('./', import.meta.url)
const destination = new URL('../hydrodb-requirements/docs/frontend/timeseries-graph.html', root)
const source = 'https://www.pegelonline.wsv.de/webservices/rest-api/v2/stations/0d8233b8-36c9-4a24-ad77-a4e7c617932f/W/measurements.json?start=P7D'
const read = (path) => readFile(new URL(path, root), 'utf8')
const json = (value) => JSON.stringify(value).replaceAll('<', '\\u003c')
const refresh = process.argv.includes('--refresh')
const dwdInput = process.argv.find((arg) => arg.startsWith('--dwd-snapshot='))
const previous = refresh && dwdInput ? undefined : await readFile(destination, 'utf8').catch((error) => {
  if (error.code !== 'ENOENT') throw error
  throw new Error('No existing graph preview. To rebuild with new snapshots, use --refresh --dwd-snapshot=<path>.', { cause: error })
})
function embeddedSnapshot(id) {
  const embedded = previous && new RegExp(`<script id="${id}" type="application/json">([^<]+)</script>`).exec(previous)
  if (!embedded) throw new Error(`Could not find the embedded ${id}.`)
  return JSON.parse(embedded[1])
}
let snapshot
if (refresh) {
  const readings = JSON.parse(execFileSync('curl', ['-fsS', '--max-time', '30', source], { encoding: 'utf8' }))
  snapshot = { captured: new Date().toISOString(), readings: readings.map(({ timestamp, value }) => [timestamp, value]) }
} else {
  snapshot = embeddedSnapshot('snapshot')
}
if (!Number.isFinite(Date.parse(snapshot.captured)) || !Array.isArray(snapshot.readings) ||
    !snapshot.readings.length || snapshot.readings.length > 20_000) throw new Error('Invalid snapshot size or capture timestamp.')
let previousTime = -Infinity
for (const [timestamp, value] of snapshot.readings) {
  const time = Date.parse(timestamp)
  if (!Number.isFinite(time) || time <= previousTime || !Number.isFinite(value)) throw new Error('Invalid or unordered provider reading.')
  previousTime = time
}
const dwd = dwdInput ? JSON.parse(await readFile(dwdInput.slice('--dwd-snapshot='.length), 'utf8')) :
  embeddedSnapshot('dwd-snapshot')
if (!Number.isFinite(Date.parse(dwd.captured)) || !Array.isArray(dwd.readings) ||
    !dwd.readings.length || dwd.readings.length > 20_000) throw new Error('Invalid DWD snapshot.')
previousTime = -Infinity
for (const row of dwd.readings) {
  const end = Date.parse(row.period_end)
  const start = Date.parse(row.period_start)
  if (row.timestamp !== row.period_end || !Number.isFinite(end) || end <= previousTime ||
      end % 60_000 !== 0 || !Number.isFinite(start) || start >= end ||
      !['valid', 'missing'].includes(row.state) ||
      (row.state === 'valid' ? typeof row.value !== 'string' || !/^\d+(?:\.\d{1,2})?$/.test(row.value) :
        row.value !== null)) throw new Error('Invalid or unordered DWD accumulation.')
  previousTime = end
}
const [bundle, baseCss, appCss, ...licenses] = await Promise.all([
  build({
    configFile: false, plugins: [react()], root: fileURLToPath(root), logLevel: 'warn',
    define: { 'process.env.NODE_ENV': '"production"' },
    build: { write: false, lib: { entry: fileURLToPath(new URL('src/preview/TimeseriesGraph.tsx', root)), name: 'TimeseriesPreview', formats: ['iife'] } },
  }),
  read('src/index.css'), read('src/App.css'),
  ...['node_modules/react/LICENSE', 'node_modules/react-dom/LICENSE', 'node_modules/scheduler/LICENSE', 'public/assets/echarts-LICENSE.txt',
    'public/assets/echarts-NOTICE.txt', 'public/assets/echarts-d3-LICENSE.txt', 'public/assets/zrender-LICENSE.txt'].map(read),
])
const output = Array.isArray(bundle) ? bundle[0]?.output : bundle.output
const chunk = output?.find((entry) => entry.type === 'chunk' && entry.isEntry)
if (!chunk || output.length !== 1) throw new Error('The preview must compile to one self-contained script.')

await writeFile(destination, `<!doctype html>
<!-- Generated by hydrodb-frontend/build-timeseries-preview.mjs. Edit the shared chart and rebuild. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>HydroDB offline graph preview</title>
<style>${baseCss}\n${appCss}
#preview { height: 100dvh; }
#preview h1 { margin: 0; }
#preview .preview-heading { display: flex; flex-wrap: wrap; align-items: center; gap: 4px 12px; }
#preview .preview-heading label { display: flex; align-items: center; gap: 6px; min-width: 0; max-width: 100%; }
#preview .preview-heading select { width: auto; min-width: 0; height: var(--control-height); }
#preview header p { margin: 2px 0; overflow-wrap: anywhere; }
#preview .sample-figure { margin-top: 6px; }
#preview footer { margin-top: 4px; font-size: .875rem; }
</style>
</head>
<body>
<main id="preview"></main>
<noscript>This offline graph requires JavaScript to render.</noscript>
<script id="snapshot" type="application/json">${json(snapshot)}</script>
<script id="dwd-snapshot" type="application/json">${json(dwd)}</script>
<script>${chunk.code.replaceAll(/<\/script/gi, '<\\/script')}</script>
<template id="third-party-licenses">${licenses.join('\n\n').replaceAll('&', '&amp;').replaceAll('<', '&lt;')}</template>
</body>
</html>
`)
console.log(`Saved ${snapshot.readings.length} PEGELONLINE and ${dwd.readings.length} DWD readings to ${fileURLToPath(destination)}`)
