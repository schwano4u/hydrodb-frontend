import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import react from '@vitejs/plugin-react'
import { build } from 'vite'

const root = new URL('./', import.meta.url)
const destination = new URL('../hydrodb-requirements/docs/frontend/components.html', root)
const [bundle, ...licenses] = await Promise.all([
  build({
    configFile: false,
    root: fileURLToPath(root),
    plugins: [react()],
    logLevel: 'warn',
    define: { 'process.env.NODE_ENV': '"production"' },
    build: {
      write: false,
      lib: { entry: fileURLToPath(new URL('src/componentsMain.tsx', root)), name: 'ComponentsPreview', formats: ['iife'] },
    },
  }),
  ...['react', 'react-dom', 'scheduler'].map((pkg) => readFile(new URL(`node_modules/${pkg}/LICENSE`, root), 'utf8')),
  ...['echarts-LICENSE.txt', 'echarts-NOTICE.txt', 'echarts-d3-LICENSE.txt', 'zrender-LICENSE.txt']
    .map((file) => readFile(new URL(`public/assets/${file}`, root), 'utf8')),
])

const output = (Array.isArray(bundle) ? bundle[0] : bundle).output
const script = output.find((item) => item.type === 'chunk' && item.isEntry)
const styles = output.find((item) => item.type === 'asset' && item.fileName.endsWith('.css'))
if (!script || !styles || output.length !== 2) {
  throw new Error('The component preview must compile to one script and one stylesheet.')
}

await writeFile(destination, `<!doctype html>
<!-- Generated by hydrodb-frontend/build-components-preview.mjs. Edit the React components and regenerate. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="description" content="Interactive examples of the reusable HydroDB frontend components." />
    <title>HydroDB GUI components</title>
    <style>${styles.source}</style>
  </head>
  <body>
    <div id="root"></div>
    <noscript>Enable JavaScript to use the interactive component demo.</noscript>
    <script>${script.code.replaceAll(/<\/script/gi, '<\\/script')}</script>
    <template id="third-party-licenses">${licenses.join('\n\n').replaceAll('&', '&amp;').replaceAll('<', '&lt;')}</template>
  </body>
</html>
`)
console.log(`Saved ${fileURLToPath(destination)}`)
